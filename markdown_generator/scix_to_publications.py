#!/usr/bin/env python3
"""Convert a SciX/ADS BibTeX export into Academic Pages publication files.

Usage (from the repository root):

    python3 markdown_generator/scix_to_publications.py markdown_generator/export-bibtex.bib

To update the list later, re-export the BibTeX from SciX and run the command again.
Files previously generated by this script (marked with `source: scix`) are replaced;
any publication files you wrote by hand are left alone.

No extra Python packages are needed.
"""

import json
import re
import sys
import unicodedata
from pathlib import Path

ME = "Gebek"  # surname to highlight and to decide first-author vs co-authored
MAX_AUTHORS_SHOWN = 3  # in the list view; full author list is on each paper's page

OUT_DIR = Path(__file__).resolve().parent.parent / "_publications"

JOURNALS = {
    r"\mnras": "MNRAS",
    r"\aap": "A&A",
    r"\apj": "ApJ",
    r"\apjl": "ApJL",
    r"\apjs": "ApJS",
    r"\aj": "AJ",
    r"\nat": "Nature",
    r"\natas": "Nature Astronomy",
    r"\pasp": "PASP",
    r"\araa": "ARA&A",
    r"\mnrasl": "MNRAS Letters",
}

MONTHS = {m: i for i, m in enumerate(
    ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"], 1)}

ACCENTS = {"'": "\u0301", "`": "\u0300", "^": "\u0302", '"': "\u0308", "~": "\u0303",
           "=": "\u0304", ".": "\u0307", "u": "\u0306", "v": "\u030c", "H": "\u030b",
           "c": "\u0327", "k": "\u0328", "r": "\u030a", "textcommabelow": "\u0326"}

GREEK = {name: chr(0x3B1 + i) for i, name in enumerate(
    ["alpha", "beta", "gamma", "delta", "epsilon", "zeta", "eta", "theta", "iota", "kappa",
     "lambda", "mu", "nu", "xi", "omicron", "pi", "rho", "varsigma", "sigma", "tau",
     "upsilon", "phi", "chi", "psi", "omega"])}


def delatex(s):
    """Turn the LaTeX found in ADS exports into plain text / simple HTML."""
    s = re.sub(r"\\ensuremath\{(.*?)\}", r"\1", s)
    s = re.sub(r"\\(" + "|".join(GREEK) + r")\b", lambda m: GREEK[m.group(1)], s)
    s = s.replace(r"\i", "i").replace(r"\&", "&").replace("--", "–")
    # accents: {\'e}, \'{e}, \v{c}, {\textcommabelow s}, ...
    acc = "|".join(re.escape(k) for k in sorted(ACCENTS, key=len, reverse=True))
    s = re.sub(r"\\(" + acc + r")\s*\{?\s*([A-Za-z])\}?",
               lambda m: m.group(2) + ACCENTS[m.group(1)], s)
    s = s.replace("~", " ")  # LaTeX non-breaking space (after accents, which use \~)
    # simple math: $_{2}$ -> <sub>2</sub>, $^{+}$ -> <sup>+</sup>
    s = re.sub(r"\$_\{?([^}$]*)\}?\$", r"<sub>\1</sub>", s)
    s = re.sub(r"\$\^\{?([^}$]*)\}?\$", r"<sup>\1</sup>", s)
    s = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", s)
    s = s.replace("$", "").replace("{", "").replace("}", "")
    return unicodedata.normalize("NFC", re.sub(r"\s+", " ", s).strip())


def parse_bibtex(text):
    """Minimal parser for the (very regular) BibTeX that SciX/ADS exports."""
    entries = []
    for chunk in re.split(r"\n(?=@)", text.strip()):
        m = re.match(r"@(\w+)\{([^,]+),", chunk)
        if not m:
            continue
        fields = {}
        for line in chunk.splitlines()[1:]:
            fm = re.match(r"\s*(\w+)\s*=\s*(.*?),?\s*$", line)
            if fm:
                val = fm.group(2)
                if val.startswith('"') and val.endswith('"'):
                    val = val[1:-1]
                if val.startswith("{") and val.endswith("}"):
                    val = val[1:-1]
                fields[fm.group(1).lower()] = val
        entries.append({"type": m.group(1).lower(), "key": m.group(2), **fields})
    return entries


def split_authors(field):
    """Return (list of 'A. B. Surname' strings, index of ME or None, truncated?)."""
    raw = [a.strip() for a in re.split(r"\s+and\s+", field)]
    truncated = raw and raw[-1] == "et al."
    if truncated:
        raw = raw[:-1]
    names, me = [], None
    for i, a in enumerate(raw):
        last, _, first = a.partition(",")
        last, first = delatex(last), delatex(first)
        initials = " ".join(
            "-".join(p[0] + "." for p in part.split("-") if p)
            for part in first.replace(".", ". ").split() if part)
        names.append(f"{initials} {last}".strip())
        if me is None and last == ME:
            me = i
    return names, me, truncated


def bold(name):
    return f"<b>{name}</b>"


def short_authors(names, me, truncated):
    shown = [bold(n) if i == me else n for i, n in enumerate(names[:MAX_AUTHORS_SHOWN])]
    last_shown = MAX_AUTHORS_SHOWN - 1
    if me is not None and me > last_shown:
        if me > MAX_AUTHORS_SHOWN:
            shown.append("…")
        shown.append(bold(names[me]))
        last_shown = me
    more = truncated or len(names) > last_shown + 1
    text = ", ".join(shown)
    if more:
        text += ", et al."
    if me is None:  # ADS truncated the author list before reaching us
        text += f" (incl. {bold('A. ' + ME)})"
    return text


def full_authors(names, me, truncated):
    text = ", ".join(bold(n) if i == me else n for i, n in enumerate(names))
    if truncated:
        text += ", et al."
    if me is None:
        text += f" (incl. {bold('A. ' + ME)})"
    return text


def slugify(s, maxlen=60):
    s = unicodedata.normalize("NFKD", re.sub(r"<[^>]+>", "", s)).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-zA-Z0-9]+", "-", s).strip("-").lower()
    return s[:maxlen].rstrip("-")


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML


def links(e):
    out = []
    if e.get("doi"):
        out.append(f"[Journal](https://doi.org/{e['doi']})")
    if e.get("eprint"):
        out.append(f"[arXiv](https://arxiv.org/abs/{e['eprint']})")
    out.append(f"[SciX](https://scixplorer.org/abs/{e['key'].replace('&', '%26')}/abstract)")
    return " · ".join(out)


def main(bibfile):
    entries = parse_bibtex(Path(bibfile).read_text(encoding="utf-8"))

    OUT_DIR.mkdir(exist_ok=True)
    removed = 0
    for f in OUT_DIR.glob("*.md"):
        if "\nsource: scix\n" in f.read_text(encoding="utf-8"):
            f.unlink()
            removed += 1

    written = 0
    for e in entries:
        title = delatex(e.get("title", ""))
        year = e.get("year", "1900")
        month = MONTHS.get(e.get("month", "jan")[:3].lower(), 1)
        date = f"{year}-{month:02d}-01"
        venue = JOURNALS.get(e.get("journal", ""), delatex(e.get("journal", e.get("booktitle", ""))))
        names, me, truncated = split_authors(e.get("author", ""))
        category = "firstauthor" if me == 0 else "coauthor"

        ref = venue
        if e.get("volume"):
            ref += f", {e['volume']}"
        if e.get("pages") or e.get("eid"):
            ref += f", {e.get('pages') or e.get('eid')}"

        slug = f"{date}-{slugify(title)}"
        fm = [
            "---",
            f"title: {yaml_str(title)}",
            "collection: publications",
            f"category: {category}",
            f"permalink: /publication/{slug}",
            f"date: {date}",
            f"venue: {yaml_str(venue)}",
            f"excerpt: {yaml_str(short_authors(names, me, truncated) + '<br>' + links(e))}",
        ]
        if e.get("eprint"):
            fm.append(f"paperurl: {yaml_str('https://arxiv.org/pdf/' + e['eprint'])}")
        fm += [f"bibcode: {yaml_str(e['key'])}", "source: scix", "---", ""]

        body = [
            f"**Authors:** {full_authors(names, me, truncated)}",
            "",
            f"**Published in:** *{ref}* ({year})",
            "",
            links(e),
            "",
        ]
        (OUT_DIR / f"{slug}.md").write_text("\n".join(fm + body), encoding="utf-8")
        written += 1

    print(f"Removed {removed} previously generated file(s); wrote {written} publication(s) to {OUT_DIR}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
